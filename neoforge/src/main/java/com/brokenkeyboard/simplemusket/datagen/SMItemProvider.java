package com.brokenkeyboard.simplemusket.datagen;

import com.brokenkeyboard.simplemusket.Constants;
import com.brokenkeyboard.simplemusket.ModRegistry;
import net.minecraft.core.HolderLookup;
import net.minecraft.data.PackOutput;
import net.minecraft.tags.ItemTags;
import net.neoforged.neoforge.common.data.ItemTagsProvider;

import java.util.concurrent.CompletableFuture;

public class SMItemProvider extends ItemTagsProvider {

    public SMItemProvider(PackOutput output, CompletableFuture<HolderLookup.Provider> lookupProvider) {
        super(output, lookupProvider, Constants.MOD_ID);
    }

    @Override
    protected void addTags(HolderLookup.Provider provider) {
        tag(SMDataPackProvider.MUSKET_ENCHANTABLE).add(ModRegistry.MUSKET.value());
        tag(ItemTags.DURABILITY_ENCHANTABLE).add(ModRegistry.MUSKET.value());
    }
}